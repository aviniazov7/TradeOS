// Split off the period token and strip period + month/quarter parens, leaving
// the normalized dictionary key.
function normalize(title) {
  const s = String(title || '').trim();
  let period = '';
  const pm = s.match(/\b(m\/m|mom|y\/y|yoy|q\/q|qoq)\b/i);
  if (pm) {
    const p = pm[1].toLowerCase();
    period = p === 'mom' ? 'm/m' : p === 'yoy' ? 'y/y' : p === 'qoq' ? 'q/q' : p;
  }
  const base = s
    .replace(/\b(m\/m|mom|y\/y|yoy|q\/q|qoq)\b/ig, ' ')
    .replace(/\((jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\)/ig, ' ')
    .replace(/\(q[1-4]\)/ig, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
  return { base, period };
}

// Returns the professional Hebrew title, or null if not in the dictionary.
export function hebrewEventTitle(title) {
  const { base, period } = normalize(title);
  let he = CAL_TERMS[base];
  // Retry without a leading country/adjective ("German Ifo ..." -> "ifo ...").
  if (!he && base.includes(' ')) he = CAL_TERMS[base.slice(base.indexOf(' ') + 1)];
  if (!he) return null;
  return period && PERIOD_HE[period] ? he + ' (' + PERIOD_HE[period] + ')' : he;
}
